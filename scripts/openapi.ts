#!/usr/bin/env node
/**
 * Emit `docs/openapi.yaml` from the OpenAPI document in `openapi-doc.ts`.
 *
 *   npm run openapi
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { stringify } from "yaml";
import { buildOpenApiDocument } from "./openapi-doc.ts";

const GENERATED_HEADER = "# Generated by `npm run openapi`. Edit scripts/openapi-doc.ts (patches) and scripts/openapi-base.ts (operations), then rerun.\n";

export function renderOpenApi(): string {
  return `${GENERATED_HEADER}${stringify(buildOpenApiDocument(), { lineWidth: 0, aliasDuplicateObjects: false })}\n`;
}

const here = dirname(fileURLToPath(import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(here, "../docs/openapi.yaml");
  writeFileSync(out, renderOpenApi());
  process.stdout.write(`wrote ${out}\n`);
}
