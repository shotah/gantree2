#!/usr/bin/env node
/**
 * Emit the theme catalog for the native apps. `lib/theme/catalog.ts` is the
 * only place a hex lives; cab (Kotlin) and helm (Swift) consume what this
 * writes and never hand-copy a color again.
 *
 *   node scripts/theme-export.ts <outDir> [--kotlin-package com.gantree.theme]
 *
 * Writes: tokens.json · GantreeThemes.kt · GantreeThemes.swift
 *
 * Runs on Node >= 22.18 (type stripping on by default). Fields are every
 * ThemeTokens key; apps map the ones they paint.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_THEME, THEMES, type ThemeDef } from "../lib/theme/catalog.ts";

const HEADER = "Generated by gantree scripts/theme-export.ts from lib/theme/catalog.ts. Do not edit.";

type Row = Pick<ThemeDef, "id" | "label" | "feel" | "mood"> & { tokens: Record<string, string> };

export function rows(themes: readonly ThemeDef[] = THEMES): Row[] {
  return themes.map((t) => ({ id: t.id, label: t.label, feel: t.feel, mood: t.mood, tokens: { ...t.tokens } }));
}

export function tokenKeys(themes: readonly ThemeDef[] = THEMES): string[] {
  return Object.keys(themes[0].tokens).filter((k) => k !== "scheme");
}

export function json(themes: readonly ThemeDef[] = THEMES): string {
  return `${JSON.stringify({ generated: HEADER, default: DEFAULT_THEME, themes: rows(themes) }, null, 2)}\n`;
}

/** `#rrggbb` → `0xFFRRGGBB` (Compose Color) or `0xRRGGBB` (helm's UInt32). */
function argb(hex: string, alpha: boolean): string {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) {
    throw new Error(`not a #rrggbb hex: ${hex}`);
  }
  return `0x${alpha ? "FF" : ""}${m[1].toUpperCase()}`;
}

export function kotlin(themes: readonly ThemeDef[] = THEMES, pkg = "com.gantree.theme"): string {
  const keys = tokenKeys(themes);
  const fields = keys.map((k) => `  val ${k}: Color,`).join("\n");
  const entries = themes.map((t) => {
    const vals = keys.map((k) => `      ${k} = Color(${argb(t.tokens[k as keyof typeof t.tokens], true)}),`).join("\n");
    return `    "${t.id}" to GantreeTheme(\n      id = "${t.id}",\n      label = "${t.label}",\n      feel = "${t.feel}",\n      scheme = "${t.tokens.scheme}",\n      mood = ${JSON.stringify(t.mood)},\n${vals}\n    ),`;
  }).join("\n");
  return `// ${HEADER}
package ${pkg}

import androidx.compose.ui.graphics.Color

data class GantreeTheme(
  val id: String,
  val label: String,
  val feel: String,
  val scheme: String,
  val mood: String,
${fields}
)

object GantreeThemes {
  const val DEFAULT = "${DEFAULT_THEME}"

  val all: Map<String, GantreeTheme> = linkedMapOf(
${entries}
  )

  val ids: List<String> = all.keys.toList()

  /** Unknown or null → the default, same as the Worker's parseTheme. */
  fun of(id: String?): GantreeTheme = all[id] ?: all.getValue(DEFAULT)
}
`;
}

export function swift(themes: readonly ThemeDef[] = THEMES): string {
  const keys = tokenKeys(themes);
  const fields = keys.map((k) => `  public let ${k}: UInt32`).join("\n");
  const entries = themes.map((t) => {
    const vals = keys.map((k) => `      ${k}: ${argb(t.tokens[k as keyof typeof t.tokens], false)},`).join("\n");
    return `    "${t.id}": GantreeTheme(\n      id: "${t.id}", label: "${t.label}", feel: "${t.feel}", scheme: "${t.tokens.scheme}",\n      mood: ${JSON.stringify(t.mood)},\n${vals}\n    ),`;
  }).join("\n");
  return `// ${HEADER}

/// Values are 0xRRGGBB (opaque). SwiftUI maps them in the app target.
public struct GantreeTheme: Equatable, Sendable {
  public let id: String
  public let label: String
  public let feel: String
  public let scheme: String
  public let mood: String
${fields}
}

public enum GantreeThemes {
  public static let defaultId = "${DEFAULT_THEME}"

  public static let all: [String: GantreeTheme] = [
${entries}
  ]

  public static let ids: [String] = [${themes.map((t) => `"${t.id}"`).join(", ")}]

  /// Unknown or nil → the default, same as the Worker's parseTheme.
  public static func of(_ id: String?) -> GantreeTheme {
    if let id, let t = all[id] { return t }
    return all[defaultId]!
  }
}
`;
}

export function main(argv: string[]): string[] {
  const [outDir, ...rest] = argv;
  if (!outDir) {
    throw new Error("usage: theme-export.ts <outDir> [--kotlin-package pkg]");
  }
  const i = rest.indexOf("--kotlin-package");
  const pkg = i >= 0 ? rest[i + 1] : "com.gantree.theme";
  mkdirSync(outDir, { recursive: true });
  const out = [
    ["tokens.json", json()],
    ["GantreeThemes.kt", kotlin(THEMES, pkg)],
    ["GantreeThemes.swift", swift()],
  ] as const;
  for (const [name, body] of out) {
    writeFileSync(join(outDir, name), body);
  }
  return out.map(([name]) => join(outDir, name));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    for (const f of main(process.argv.slice(2))) {
      process.stdout.write(`wrote ${f}\n`);
    }
  } catch (err) {
    process.stderr.write(`${err instanceof Error ? err.message : String(err)}\n`);
    process.exit(1);
  }
}
